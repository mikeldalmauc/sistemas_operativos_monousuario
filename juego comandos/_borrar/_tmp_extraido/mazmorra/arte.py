_ACENTOS = str.maketrans("ÁÉÍÓÚÑÜ", "AEIOUNU")


def rotulo(texto: str) -> list[str]:
    """Devuelve el texto en letras grandes (lista de 5 líneas)."""
    texto = texto.upper().translate(_ACENTOS)
    filas = [""] * 5
    for letra in texto:
        glifo = _FUENTE.get(letra, _FUENTE[" "])
        for i in range(5):
            filas[i] += glifo[i] + " "
    return [f.rstrip() for f in filas]


